def _dayun_shi_shen_cards(dayun: list, day_gan: str) -> list:
    """从大运干支里提取十神，匹配大运解读卡。"""
    cards = []
    seen = set()
    for d in dayun[:4]:
        gz = d["ganzhi"]
        if len(gz) < 2:
            continue
        gan, zhi = gz[0], gz[1]
        ss = shi_shen(day_gan, gan)
        key = f"{ss}"
        if key in DAYUN_KB and key not in seen:
            seen.add(key)
            cards.append(f"【{gz} 大运（{d['start_age']}~{d['end_age']}岁）】天干{gan}为{ss}——{DAYUN_KB[key]}")
    return cards


def _combo_cards(pillars: dict) -> list:
    """扫描四柱十神，命中组合卡。"""
    cards = []
    all_ss = set()
    for name in ("year", "month", "time"):
        d = pillars[name]
        if d["shi_shen_gan"]:
            all_ss.add(d["shi_shen_gan"])
        all_ss.update(d["shi_shen_zhi"])
    def hit(a, b):
        return a in all_ss and b in all_ss
    combos = [
        ("食神生财", hit("食神", "正财") or hit("食神", "偏财")),
        ("伤官配印", hit("伤官", "正印") or hit("伤官", "偏印")),
        ("财官相生", (hit("正财", "正官") or hit("偏财", "正官"))),
        ("食神制杀", hit("食神", "七杀")),
        ("伤官见官", hit("伤官", "正官")),
        ("印星护身", hit("正印", "比肩") or hit("偏印", "比肩")),
        ("比劫帮身", ("比肩" in all_ss or "劫财" in all_ss)),
        ("官杀混杂", hit("正官", "七杀")),
    ]
    for name, ok in combos:
        if ok and name in COMBO_KB:
            cards.append(f"【格局·{name}】{COMBO_KB[name]}")
    return cards



def chart_facts(chart: dict) -> str:
    """把排盘 dict 压成给模型看的结构化事实块。"""
    p = chart["pillars"]
    lines = []
    lines.append(f"公历 {chart['solar']}（{chart['lunar']}，生肖{chart['zodiac']}）")
    if chart.get("place"):
        lines.append(f"出生地：{chart['place']}")
    lines.append(f"性别：{chart['gender']}　时间精度：{'精确到分钟' if chart.get('time_precise') else '大概回忆（降级轨道：少断具体事件，多用性格与趋势描述）'}")
    for name, label in (("year", "年柱"), ("month", "月柱"), ("day", "日柱"), ("time", "时柱")):
        d = p[name]
        ss = d["shi_shen_gan"] or "日主"
        lines.append(
            f"{label} {d['ganzhi']}（{d['nayin']}）天干{d['gan_element']}/地支{d['zhi_element']}，"
            f"藏干{'、'.join(d['hidden_gan'])}，十神：干-{ss} 支-{'、'.join(d['shi_shen_zhi'])}"
        )
    w = chart["wuxing_count"]
    lines.append(f"日主：{chart['day_master']}（{chart['day_master_element']}）")
    lines.append(f"五行分布（天干地支本气数）：{' '.join(f'{k}{v}' for k, v in w.items())}；最旺{chart['wuxing_strongest']}"
                 + (f"；缺{'、'.join(chart['wuxing_missing'])}" if chart["wuxing_missing"] else "；五行俱全"))
    # 月令为提纲：考虑季节与藏干权重的真实五行力量（命理学的关键，避免把冬月火误判为旺）
    if chart.get("wuxing_normalized") and chart.get("month_zhi"):
        wn = chart["wuxing_normalized"]
